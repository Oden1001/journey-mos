Status ReadStatus() {
  Status st;
  auto path = Join(GameDir(), L"mod_status.json");
  std::ifstream in(path.c_str());
  if (!in) return st;
  std::stringstream ss;
  ss << in.rdbuf();
  auto s = ss.str();
  auto has = [&](const char* key) {
    return s.find(std::string("\"") + key + "\":true") != std::string::npos;
  };
  st.ok = s.find("\"ok\":true") != std::string::npos;
  st.energy = has("energy");
  st.speed = has("speed");
  st.farm = has("farm") || has("autoFarm");
  auto lp = s.find("\"level\":\"");
  if (lp != std::string::npos) {
    lp += 9;
    auto e = s.find('"', lp);
    if (e != std::string::npos) st.level = s.substr(lp, e - lp);
  }
  auto sp = s.find("\"speedMult\":");
  if (sp != std::string::npos) st.speedMult = (float)atof(s.c_str() + sp + 12);
  auto gs = s.find("\"gameSpeed\":");
  if (gs != std::string::npos) st.gameSpeed = (float)atof(s.c_str() + gs + 12);
  auto sy = s.find("\"symbols\":");
  if (sy != std::string::npos) st.symbols = atoi(s.c_str() + sy + 10);
  return st;
}

