#!/usr/bin/env python3
"""Generate native/Launcher/embedded_payloads.{h,cpp} from mod/*.lua (+ Tick.lua.gz).

Run automatically from native/build.bat before compiling the launcher.
"""

from __future__ import annotations

import struct
import sys
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MOD = ROOT / "mod"
OUT_H = ROOT / "native" / "Launcher" / "embedded_payloads.h"
OUT_CPP = ROOT / "native" / "Launcher" / "embedded_payloads.cpp"

HOOK_MARKER = "v5-once"

# Runtime scripts released next to Journey.exe.
# only_if_missing: don't clobber user/menu-written files.
SCRIPTS = [
    ("StartLua.lua", False),
    ("TickHook.lua", False),
    ("GameTick.lua", False),
    ("features.lua", False),
    ("RunOnce.lua", False),
    ("config.lua", True),
    ("commands.lua", True),
]


def make_tick_gz(raw: bytes) -> bytes:
    if raw.startswith(b"\xef\xbb\xbf"):
        raw = raw[3:]
    seven = ROOT / "tools" / "bin" / "7za.exe"
    if seven.exists():
        import subprocess
        import tempfile

        with tempfile.TemporaryDirectory() as td:
            td_path = Path(td)
            src = td_path / "Tick.lua"
            src.write_bytes(raw)
            gz_path = td_path / "Tick.lua.gz"
            subprocess.check_call(
                [str(seven), "a", "-tgzip", "-y", str(gz_path), str(src)],
                cwd=td,
                stdout=subprocess.DEVNULL,
                stderr=subprocess.DEVNULL,
            )
            return gz_path.read_bytes()

    filename = b"Tick.lua\x00"
    header = b"\x1f\x8b\x08\x08" + struct.pack("<I", 0) + b"\x00\x00" + filename
    compressor = zlib.compressobj(9, zlib.DEFLATED, -zlib.MAX_WBITS)
    body = compressor.compress(raw) + compressor.flush()
    trailer = struct.pack("<II", zlib.crc32(raw) & 0xFFFFFFFF, len(raw) & 0xFFFFFFFF)
    return header + body + trailer


def c_bytes(symbol: str, data: bytes) -> str:
    lines = [f"static const unsigned char {symbol}_data[] = {{"]
    for i in range(0, len(data), 16):
        chunk = ", ".join(f"0x{b:02x}" for b in data[i : i + 16])
        lines.append(f"  {chunk},")
    lines.append("};")
    return "\n".join(lines)


def main() -> int:
    tick_path = MOD / "Tick.lua"
    if not tick_path.exists():
        print(f"[!] missing {tick_path}", file=sys.stderr)
        return 1

    tick_gz = make_tick_gz(tick_path.read_bytes())
    print(f"[+] Tick.lua.gz = {len(tick_gz)} bytes")

    script_blobs: list[tuple[str, bytes, bool]] = []
    for name, only_missing in SCRIPTS:
        path = MOD / name
        if not path.exists():
            print(f"[!] missing {path}", file=sys.stderr)
            return 1
        script_blobs.append((name, path.read_bytes(), only_missing))
        print(f"[+] {name} = {path.stat().st_size} bytes")

    OUT_H.parent.mkdir(parents=True, exist_ok=True)
    OUT_H.write_text(
        """#pragma once

// Auto-generated by tools/gen_launcher_payloads.py — do not edit.

struct EmbeddedScript {
  const char* name;
  const unsigned char* data;
  unsigned size;
  int onlyIfMissing;  // 1 = write only when file absent
};

extern const unsigned char* kTickLuaGz;
extern const unsigned kTickLuaGzLen;
extern const char kHookMarker[];
extern const EmbeddedScript kEmbeddedScripts[];
extern const unsigned kEmbeddedScriptCount;
""",
        encoding="utf-8",
    )

    parts: list[str] = [
        '// Auto-generated by tools/gen_launcher_payloads.py — do not edit.\n',
        '#include "embedded_payloads.h"\n',
        c_bytes("kTickGz", tick_gz),
        "\nconst unsigned char* kTickLuaGz = kTickGz_data;",
        f"\nconst unsigned kTickLuaGzLen = {len(tick_gz)};",
        f'\nconst char kHookMarker[] = "{HOOK_MARKER}";\n',
    ]

    for i, (_, data, _) in enumerate(script_blobs):
        parts.append("\n" + c_bytes(f"kScript{i}", data))

    parts.append("\nconst EmbeddedScript kEmbeddedScripts[] = {")
    for i, (name, data, only_missing) in enumerate(script_blobs):
        flag = 1 if only_missing else 0
        parts.append(
            f'  {{ "{name}", kScript{i}_data, {len(data)}, {flag} }},'
        )
    parts.append("};")
    parts.append(f"\nconst unsigned kEmbeddedScriptCount = {len(script_blobs)};\n")

    OUT_CPP.write_text("\n".join(parts), encoding="utf-8")
    print(f"[+] wrote {OUT_H}")
    print(f"[+] wrote {OUT_CPP}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
